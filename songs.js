const SONG_POOL = (() => {
    const seen = new Set();
    const pool = [];
    Object.keys(SONGS_BY_ARTIST).forEach((artist) => {
        SONGS_BY_ARTIST[artist].forEach((title) => {
            const key = `${artist}|${title}`.toLowerCase();
            if (seen.has(key)) return;
            seen.add(key);
            pool.push({ artist, title });
        });
    });
    return pool;
})();
